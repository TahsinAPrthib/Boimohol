export function describe(w: { titleBangla: string; authors: string[]; translators: string[]; form: Form | null }): string {
  const known = KNOWN[`${w.titleBangla}|${w.authors[0]}`];
  if (known) return known;
  const noun = w.form?.noun ?? "বই";
  const by = possessive(listOf(w.authors));
  if (w.translators.length) return `${by} ${noun}, ${possessive(listOf(w.translators))} অনুবাদে।`;
  return `${by} ${noun}।`;
}
