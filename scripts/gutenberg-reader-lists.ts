// The in-site Gutenberg reader's two lists (src/lib/gutenberg/lists.json):
//
// - seed: the 1,000 most downloaded of our Gutenberg books that the reader
//   can show, stored ahead of time by .github/workflows/gutenberg-seed.yml;
// - linkOnly: books the reader never fetches, keeping only the Gutenberg
//   link: no HTML version; picture books (more than 3 MB of images and under
//   150 KB of text, which a text-only reader can't do justice to); and books
//   over 5 MB of HTML, unless they are in the seed.
//
// Sizes and download counts come from Gutenberg's catalog feed (the route
// its robot policy offers for catalog data), as a table of
// "<ebook>\t<file URL>\t<bytes>" lines plus "<ebook>\tDOWNLOADS\t<count>":
//
//   bzip2 -dc data/.gutenberg-cache/rdf-files.tar.bz2 | tar -xOf - | awk '
//     /<pgterms:ebook rdf:about="ebooks\// { match($0, /ebooks\/[0-9]+/); id = substr($0, RSTART+7, RLENGTH-7) }
//     /<pgterms:file rdf:about="/ { match($0, /about="[^"]+"/); file = substr($0, RSTART+7, RLENGTH-8) }
//     /<dcterms:extent/ { match($0, />[0-9]+</); print id "\t" file "\t" substr($0, RSTART+1, RLENGTH-2) }
//     /<pgterms:downloads/ { match($0, />[0-9]+</); print id "\tDOWNLOADS\t" substr($0, RSTART+1, RLENGTH-2) }
//   ' > data/.gutenberg-cache/extents.tsv
//
//   npx tsx scripts/gutenberg-reader-lists.ts data/.gutenberg-cache/extents.tsv
//
// "Our" books are those the catalog files link to Gutenberg (the bulk and
// curated imports).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const SEED_SIZE = 1000;
const GIANT_BYTES = 5_000_000;
const PICTURE_IMAGES = 3_000_000;
const PICTURE_TEXT = 150_000;
// Links removed from the catalog (data/catalog-corrections.md, section 1).
const REMOVED = new Set([468, 45988, 44646, 48438, 32155]);

const ours = new Set<number>();
for (const f of readdirSync("data").filter((f) => /^(gutenberg-all|gutenberg-import)-\d+\.json$/.test(f)))
  for (const row of JSON.parse(readFileSync(`data/${f}`, "utf8")) as { sources?: { url: string }[] }[])
    for (const s of row.sources ?? []) {
      const m = s.url.match(/gutenberg\.org\/ebooks\/(\d+)$/);
      if (m && !REMOVED.has(+m[1])) ours.add(+m[1]);
    }

type Sizes = { html?: number; epubImages?: number; epubPlain?: number; downloads: number };
const books = new Map<number, Sizes>();
for (const line of readFileSync(process.argv[2], "utf8").split("\n")) {
  const [idText, file, value] = line.split("\t");
  const id = Number(idText);
  if (!ours.has(id)) continue;
  const b = books.get(id) ?? { downloads: 0 };
  const n = Number(value);
  if (file === "DOWNLOADS") b.downloads = n;
  else if (file.endsWith(`/ebooks/${id}.html.images`)) b.html = n;
  else if (file.endsWith(`/ebooks/${id}.epub3.images`)) b.epubImages = n;
  else if (file.endsWith(`/ebooks/${id}.epub.noimages`)) b.epubPlain = n;
  books.set(id, b);
}

const noHtml = [...ours].filter((id) => !books.get(id)?.html);
const picture = [...books].filter(([, b]) => b.html && b.html < PICTURE_TEXT && (b.epubImages ?? 0) - (b.epubPlain ?? 0) > PICTURE_IMAGES).map(([id]) => id);
const pictureSet = new Set(picture);
const readable = [...books].filter(([id, b]) => b.html && !pictureSet.has(id)).sort((a, b) => b[1].downloads - a[1].downloads || a[0] - b[0]);
const seed = readable.slice(0, SEED_SIZE).map(([id]) => id);
const seedSet = new Set(seed);
const giants = readable.filter(([id, b]) => b.html! > GIANT_BYTES && !seedSet.has(id)).map(([id]) => id);
const linkOnly = [...new Set([...noHtml, ...picture, ...giants])].sort((a, b) => a - b);

const seedBytes = seed.reduce((n, id) => n + (books.get(id)!.html ?? 0), 0);
writeFileSync(
  "src/lib/gutenberg/lists.json",
  JSON.stringify(
    {
      note: "Generated by scripts/gutenberg-reader-lists.ts from Gutenberg's catalog feed; see that script.",
      counts: { books: ours.size, seed: seed.length, seedHtmlBytes: seedBytes, linkOnly: linkOnly.length, noHtml: noHtml.length, picture: picture.length, giants: giants.length },
      seed,
      linkOnly,
    },
    null,
    1
  ).replace(/\n {2,}(\d+),?/g, (m) => m.replace(/\n\s+/, "")) + "\n"
);
console.log(`books ${ours.size}; seed ${seed.length} (${(seedBytes / 1e6).toFixed(0)} MB of HTML); link-only ${linkOnly.length}: no HTML ${noHtml.length}, picture books ${picture.length}, giants outside the seed ${giants.length}`);
